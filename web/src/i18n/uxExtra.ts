// English country names stored in reviews -> ISO region code, then the
// browser's own Intl.DisplayNames for the localized name (no new data set).
const COUNTRY_CODES: Record<string, string> = {
  Australia: 'AU', Brazil: 'BR', Canada: 'CA', China: 'CN', France: 'FR', Germany: 'DE', Indonesia: 'ID',
  Ireland: 'IE', Italy: 'IT', Japan: 'JP', Malaysia: 'MY', Spain: 'ES', UK: 'GB', USA: 'US', Vietnam: 'VN', Korea: 'KR',
};
const INTL_LOCALE: Record<Lang, string> = { en: 'en', ja: 'ja', zh: 'zh-CN', vi: 'vi', es: 'es', ko: 'ko' };

export function translateCountryName(lang: Lang, country: string): string {
  const code = COUNTRY_CODES[country];
  if (!code || lang === 'en') return country;
  try {
    return new Intl.DisplayNames([INTL_LOCALE[lang]], { type: 'region' }).of(code) || country;
  } catch {
    return country;
  }
}
